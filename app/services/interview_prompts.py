def get_round_scope(round_num, difficulty):
    scopes = STUDENT_ROUND_SCOPES if difficulty in STUDENT_MODES else ROUND_SCOPES
    return scopes.get(round_num, scopes[1])


def get_interaction_mode(difficulty):
    if difficulty in STUDENT_MODES:
        return STUDENT_CONTEXT + STUDENT_INTERACTION_MODES[difficulty] + STUDENT_QUESTION_PLAN
    return INTERACTION_MODES.get(difficulty, INTERACTION_MODES['标准模式'])


def get_assessment_prompt(prompt, difficulty, round_num):
    if difficulty not in STUDENT_MODES:
        return prompt
    # Replace the generic anchors so coaching and scoring use the same standard.
    base = (STUDENT_OVERALL_PROMPT if prompt == OVERALL_PROMPT
            else prompt.removesuffix(SCORE_RUBRIC))
    return (base + STUDENT_CONTEXT
            + '\n【本轮范围】' + get_round_scope(round_num, difficulty)
            + STUDENT_SCORE_RUBRICS[difficulty] + STUDENT_SCORING_GUARDS)

