/* Preserve source styles and cascade order; emit one local request per surface. */
const fs = require('node:fs');
const path = require('node:path');
const directory = path.resolve(__dirname, '../app/static/css');
const shared = ['playful.css', 'light-themes.css'];
const finish = ['playful-dark.css', 'responsive.css', 'tokens.css', 'refinement.css'];
for (const [output, foundation, utilities] of [
  ['app.bundle.css', 'ui.css', 'theme-utilities.css'],
  ['auth.bundle.css', 'auth-ui.css', 'auth-theme-utilities.css'],
]) {
  const files = [foundation, ...shared, utilities, ...finish];
  const styles = files.map(file => fs.readFileSync(path.join(directory, file), 'utf8')).join('\n');
  fs.writeFileSync(path.join(directory, output), '/* Generated by scripts/build-stylesheets.cjs; edit the source styles. */\n' + styles);
}
